def return_type(obj):
    """A function's annotated return type, unwrapped from Optional and awaitables."""
    try:
        hint = typing.get_type_hints(inspect.unwrap(obj)).get("return")
    except Exception:
        return None
    args = [a for a in typing.get_args(hint) if a is not type(None)]
    if typing.get_origin(hint) in (typing.Union, types.UnionType) and len(args) == 1:
        hint = args[0]
    return hint


def element_type(hint):
    if typing.get_origin(hint) in (list, tuple, set) and typing.get_args(hint):
        return typing.get_args(hint)[0]
    return None


DOC = "doc"


def either(texts) -> str:
    """Alternatives joined with "or", each once."""
    out = []
    for t in texts:
        for part in t.split(", or "):
            if part not in out:
                out.append(part)
    return ", or ".join(out)


def combine(*hows):
    return False if False in hows else DOC if DOC in hows else True


class Describer:
    """Turn a handler's return statements into plain sentences about the response.

    Each description is (text, how): how is True when the shape was read from the source, DOC when
    it is a helper's docstring, False when unresolved (the text is then the returned expression)."""

    def __init__(self, tables):
        self.tables = tables
        self.stats = collections.Counter()
        self.callers: list[tuple[ast.AST, int]] = []  # where a helper was called from, for its rows
        self.bound: list[dict] = []  # a helper's parameters -> (caller fn, caller node, argument)

    def row(self, fn_node, before: int, many: bool) -> str:
        """The columns of the SELECT nearest above `before`, in this function or the one that called it."""
        for node, line in [(fn_node, before)] + self.callers[::-1]:
            best = None
            for n in ast.walk(node):
                s = const(n)
                if isinstance(s, str) and n.lineno <= line:
                    m = SELECT.match(s)
                    if m and (best is None or n.lineno >= best[0]):
                        best = (n.lineno, m)
            if best is not None:
                return self.columns(best[1], many)
        return "database rows" if many else "a database row"

    def columns(self, m, many) -> str:
        cols, table = m.group(1), m.group(2)
        if cols.strip() in ("*", f"{table}.*"):
            names = self.tables.get(table, [])
        else:
            names, depth, part = [], 0, ""
            for ch in cols + ",":
                if ch == "," and depth == 0:
                    tok = part.strip()
                    alias = re.search(r"\bAS\s+(\w+)\s*$", tok, re.I)
                    names.append(alias.group(1) if alias else re.split(r"[.\s]", tok)[-1])
                    part = ""
                    continue
                depth += ch == "("
                depth -= ch == ")"
                part += ch
        listed = ", ".join(f"`{c}`" for c in names) if names else "its columns"
        return f"{'rows' if many else 'a row'} of `{table}`: {listed}"

    def assigned(self, fn_node, name, before):
        """The value last assigned to `name` above `before`, the keys set on it (or, in a loop over
        it, on each item) with x["k"] = ..., and the keys popped from it."""
        value, added, removed, item_added = None, [], [], []
        for n in own_nodes(fn_node):
            if getattr(n, "lineno", before) >= before:
                continue
            if isinstance(n, (ast.Assign, ast.AnnAssign)):
                for t in (n.targets if isinstance(n, ast.Assign) else [n.target]):
                    if isinstance(t, ast.Name) and t.id == name and n.value is not None:
                        if value is None or n.lineno >= value.lineno:
                            value = n.value
                    if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name) and t.value.id == name:
                        if isinstance(const(t.slice), str):
                            added.append(const(t.slice))
            elif isinstance(n, (ast.With, ast.AsyncWith)):
                for it in n.items:
                    if isinstance(it.optional_vars, ast.Name) and it.optional_vars.id == name:
                        value = value or it.context_expr
            elif isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr == "pop" \
                    and isinstance(n.func.value, ast.Name) and n.func.value.id == name and n.args and isinstance(const(n.args[0]), str):
                removed.append(const(n.args[0]))
            elif isinstance(n, (ast.For, ast.AsyncFor)) and isinstance(n.iter, ast.Name) and n.iter.id == name \
                    and isinstance(n.target, ast.Name):
                for m in ast.walk(n):
                    if isinstance(m, ast.Assign):
                        for t in m.targets:
                            if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name) and t.value.id == n.target.id \
                                    and isinstance(const(t.slice), str):
                                item_added.append(const(t.slice))
        return value, sorted(set(added + item_added)), sorted(set(removed))

    def type_of(self, fn, fn_node, expr, env):
        """The class an expression evaluates to, from annotations, where that can be told."""
        if isinstance(expr, ast.Await):
            return self.type_of(fn, fn_node, expr.value, env)
        if isinstance(expr, ast.Name):
            if expr.id in env:
                return env[expr.id]
            value, _, _ = self.assigned(fn_node, expr.id, getattr(expr, "lineno", 10 ** 9))
            return self.type_of(fn, fn_node, value, env) if value is not None else None
        if isinstance(expr, ast.Call):
            target = resolve(fn, expr.func)
            if target is not None:
                return return_type(target)
            if isinstance(expr.func, ast.Attribute):
                owner = self.type_of(fn, fn_node, expr.func.value, env)
                method = getattr(owner, expr.func.attr, None) if inspect.isclass(owner) else None
                if method is not None:
                    return return_type(method)
        return None

    def __call__(self, fn, expr, fn_node=None, depth=0, env=None):
        fn_node = fn_node or node_of(fn)
        env = env or {}
        line = getattr(expr, "lineno", 10 ** 9)
        if isinstance(expr, ast.Await):
            return self(fn, expr.value, fn_node, depth, env)
        if isinstance(expr, ast.Constant):
            return ("`null`" if expr.value is None else f"`{json.dumps(expr.value)}`"), True
        if isinstance(expr, ast.Dict):
            return "JSON object with " + self.fields(fn, expr, fn_node, depth, env), True
        if isinstance(expr, ast.DictComp):
            value, ok = self(fn, expr.value, fn_node, depth + 1, env)
            return f"JSON object keyed by `{unparse(expr.key)}`, each value " + value, ok
        if isinstance(expr, (ast.List, ast.Tuple, ast.Set)):
            if not expr.elts:
                return "empty JSON list", True
            item, ok = self(fn, expr.elts[0], fn_node, depth + 1, env)
            return "JSON list, each item " + item, ok
        if isinstance(expr, (ast.ListComp, ast.GeneratorExp, ast.SetComp)):
            elt, gen = expr.elt, expr.generators[0]
            if isinstance(elt, ast.Call) and callee_name(elt) == "dict":
                return "JSON list of " + self.row(fn_node, line, many=True), True
            inner = dict(env)
            if isinstance(gen.target, ast.Name):
                inner[gen.target.id] = element_type(self.type_of(fn, fn_node, gen.iter, env))
            item, ok = self(fn, elt, fn_node, depth + 1, inner)
            return "JSON list, each item " + item, ok
        if isinstance(expr, ast.IfExp):
            (a, oka), (b, okb) = self(fn, expr.body, fn_node, depth + 1, env), self(fn, expr.orelse, fn_node, depth + 1, env)
            return either([a, b]), combine(oka, okb)
        if isinstance(expr, ast.Name) and expr.id not in env and depth < 5:
            value, added, removed = self.assigned(fn_node, expr.id, line)
            text = ok = None
            if value is not None:
                text, ok = self(fn, value, fn_node, depth + 1, env)
            elif self.bound and expr.id in self.bound[-1]:
                caller_fn, caller_node, arg = self.bound[-1][expr.id]
                saved = self.bound.pop(), self.callers.pop()
                try:
                    text, ok = self(caller_fn, arg, caller_node, depth + 1, {})
                finally:
                    self.bound.append(saved[0])
                    self.callers.append(saved[1])
            if text is not None:
                added = [k for k in added if f"`{k}`" not in text]
                for key in removed:
                    text = re.sub(rf"`{re.escape(key)}`(, )?", "", text).replace(", :", ":").rstrip(", ")
                return text + (", plus " + ", ".join(f"`{k}`" for k in added) if added else ""), ok
        if isinstance(expr, ast.Call):
            return self.call(fn, expr, fn_node, depth, env, line)
        if isinstance(expr, ast.Subscript) and isinstance(const(expr.slice), str) and isinstance(expr.value, ast.Name):
            inner, ok = self(fn, expr.value, fn_node, depth + 1, env)
            if ok is True and ("row" in inner or inner.startswith("JSON object")):
                return f"the `{const(expr.slice)}` value of {inner}", True
        return f"`{unparse(expr)}`", False

    def fields(self, fn, d: ast.Dict, fn_node, depth, env) -> str:
        parts = []
        for k, v in zip(d.keys, d.values):
            if k is None:
                text, ok = self(fn, v, fn_node, depth + 1, env)
                parts.append(f"the fields of {text if ok is True else '`' + unparse(v) + '`'}")
                continue
            label = f"`{k.value}`" if isinstance(k, ast.Constant) else f"`[{unparse(k)}]`"
            if depth < 1 and isinstance(v, INTERESTING):
                text, ok = self(fn, v, fn_node, depth + 1, env)
                if ok is True and not text.startswith("`"):
                    label += f" ({text})"
            parts.append(label)
        return ", ".join(parts) if parts else "no fields"

    def call(self, fn, expr, fn_node, depth, env, line):
        name = callee_name(expr)
        if name in ("StreamingResponse", "SR", "EventSourceResponse"):
            media = const(kwarg(expr, "media_type")) or ("text/event-stream" if name == "EventSourceResponse" else None)
            return f"streamed `{media or 'application/octet-stream'}` body" + self.stream(fn, fn_node, expr), True
        if name == "FileResponse":
            media = const(kwarg(expr, "media_type"))
            return (f"a file (`{media}`)" if media else "a file, typed by its name"), True
        if name in ("Response", "PlainTextResponse", "HTMLResponse"):
            media = const(kwarg(expr, "media_type")) or {"PlainTextResponse": "text/plain", "HTMLResponse": "text/html"}.get(name)
            return (f"a `{media}` body" if media else "a raw body, with the upstream's type"), True
        if name == "RedirectResponse":
            return "a redirect (307)", True
        if name == "JSONResponse":
            code = kwarg(expr, "status_code")
            body, ok = self(fn, kwarg(expr, "content", 0), fn_node, depth + 1, env)
            return body + (f", status {status_of(code, fn)}" if code is not None else ""), ok
        if name == "json" and isinstance(expr.func, ast.Attribute) and not expr.args:
            return "the upstream service's JSON answer, passed through", True
        if name == "dict" and len(expr.args) == 1 and not expr.keywords:
            return self.row(fn_node, line, many=False), True
        if name == "fetchall":
            return self.row(fn_node, line, many=True), True
        if name == "fetchone":
            return self.row(fn_node, line, many=False), True
        if name == "asdict" and expr.args:
            cls = self.type_of(fn, fn_node, expr.args[0], env)
            if cls is not None and dataclasses.is_dataclass(cls):
                return "JSON object with " + ", ".join(f"`{f.name}`" for f in dataclasses.fields(cls)), True
        if name in ("list", "sorted", "reversed") and expr.args:
            return self(fn, expr.args[0], fn_node, depth + 1, env)
        if name in RUNNERS:
            for arg in expr.args:
                if isinstance(arg, ast.Lambda):
                    return self(fn, arg.body, fn_node, depth + 1, env)
                if isinstance(arg, ast.Name) and nested_def(fn_node, arg.id) is not None:
                    bare = ast.Call(func=arg, args=[], keywords=[])
                    return self.helper(fn, nested_def(fn_node, arg.id), (fn, fn_node, bare), line, depth, {})
        if depth >= 6:
            return f"`{unparse(expr)}`", False
        target = resolve(fn, expr.func)
        if target is not None and node_of(target) is not None:
            return self.helper(target, node_of(target), (fn, fn_node, expr), line, depth, {})
        if isinstance(expr.func, ast.Name) and nested_def(fn_node, expr.func.id) is not None:
            return self.helper(fn, nested_def(fn_node, expr.func.id), (fn, fn_node, expr), line, depth, {})
        if isinstance(expr.func, ast.Attribute):
            owner = self.type_of(fn, fn_node, expr.func.value, env)
            method = getattr(owner, expr.func.attr, None) if inspect.isclass(owner) else None
            if method is not None and node_of(method) is not None:
                return self.helper(method, node_of(method), (fn, fn_node, expr), line, depth, {"self": owner})
        return f"`{unparse(expr)}`", False

    def helper(self, fn, node, call, line, depth, env):
        """What a called helper returns, or failing that, the first sentence of its docstring."""
        caller_fn, caller_node, call_expr = call
        params = [a.arg for a in getattr(node, "args", ast.arguments([], [], None, [], [], None, [])).args]
        if params and params[0] in ("self", "cls") and "self" in env:
            params = params[1:]
        bound = {p: (caller_fn, caller_node, a) for p, a in zip(params, call_expr.args)}
        bound.update({k.arg: (caller_fn, caller_node, k.value) for k in call_expr.keywords if k.arg})
        self.callers.append((caller_node, line))
        self.bound.append(bound)
        try:
            results = self.returns(fn, node, depth + 1, env)
        finally:
            self.callers.pop()
            self.bound.pop()
        if results and all(ok is True for _, ok in results):
            return either([t for t, _ in results]), True
        doc = ast.get_docstring(node)
        if doc:
            return f"what `{getattr(node, 'name', 'it')}()` returns: " + first_sentence(doc), DOC
        return (results[0] if results else (f"`{getattr(node, 'name', '?')}()`", False))

    def stream(self, fn, fn_node, call) -> str:
        """What a streaming handler's generator yields, when it yields JSON."""
        gen = call.args[0] if call.args else kwarg(call, "content")
        target = None
        if isinstance(gen, ast.Call):
            target = nested_def(fn_node, gen.func.id) if isinstance(gen.func, ast.Name) else None
            if target is None:
                obj = resolve(fn, gen.func)
                target = node_of(obj) if obj else None
        if target is None:
            return ""
        shapes = []
        for n in own_nodes(target):
            if isinstance(n, (ast.Yield, ast.YieldFrom)) and n.value is not None:
                dumped = [c for c in ast.walk(n.value) if isinstance(c, ast.Call) and callee_name(c) == "dumps" and c.args]
                if dumped and isinstance(dumped[0].args[0], ast.Dict):
                    shape = "JSON with " + keys_of(dumped[0].args[0])
                    if shape not in shapes:
                        shapes.append(shape)
        return (", each line or event " + ", or ".join(shapes)) if shapes else ""

    def returns(self, fn, fn_node, depth=0, env=None) -> list[tuple[str, bool]]:
        out = []
        for n in own_nodes(fn_node):
            if isinstance(n, ast.Return) and n.value is not None:
                if isinstance(n.value, ast.Call) and callee_name(n.value) == "JSONResponse":
                    code = kwarg(n.value, "status_code")
                    if code is not None and str(status_of(code, fn)).startswith(("4", "5")):
                        continue  # listed with the errors
                desc = self(fn, n.value, fn_node, depth, env)
                if desc not in out:
                    out.append(desc)
        return sorted(out, key=lambda d: (d[1] is not True, d[1] is False, d[0]))


def first_sentence(doc: str) -> str:
    para = " ".join(doc.strip().split("\n\n")[0].split())
    m = re.match(r"(.+?[.!?])(\s|$)", para)
    return (m.group(1) if m else para).rstrip()


