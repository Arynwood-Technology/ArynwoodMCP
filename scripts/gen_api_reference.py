def type_of(schema: dict, refs: set) -> str:
    if not schema:
        return "any"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        refs.add(name)
        return f"[`{name}`](#schema-{name.lower()})"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            kinds = [type_of(s, refs) for s in schema[key] if s.get("type") != "null"]
            nullable = any(s.get("type") == "null" for s in schema[key])
            return " or ".join(kinds) + (" or null" if nullable else "")
    if "enum" in schema:
        return "one of " + ", ".join(f"`{json.dumps(v)}`" for v in schema["enum"])
    if "const" in schema:
        return f"`{json.dumps(schema['const'])}`"
    t = schema.get("type", "any")
    if t == "array":
        return "list of " + type_of(schema.get("items", {}), refs)
    if t == "string" and (schema.get("format") in ("binary", "base64") or "contentMediaType" in schema):
        return "file"
    if t == "object" and "additionalProperties" in schema and isinstance(schema["additionalProperties"], dict):
        return "object of " + type_of(schema["additionalProperties"], refs)
    return t


def limits(schema: dict) -> str:
    bits = []
    for key, label in (("minimum", "≥ {}"), ("exclusiveMinimum", "> {}"), ("maximum", "≤ {}"), ("exclusiveMaximum", "< {}"),
                       ("minLength", "at least {} characters"), ("maxLength", "at most {} characters"),
                       ("minItems", "at least {} items"), ("maxItems", "at most {} items"), ("pattern", "matches `{}`")):
        if key in schema:
            v = schema[key]
            bits.append(label.format(int(v) if isinstance(v, float) and v.is_integer() else v))
    for sub in schema.get("anyOf", []):
        if sub.get("type") != "null":
            extra = limits(sub)
            if extra:
                bits.append(extra)
    if schema.get("description"):
        bits.append(" ".join(schema["description"].split()))
    return "; ".join(bits)


def default_of(schema: dict) -> str:
    return f"`{json.dumps(schema['default'])}`" if "default" in schema else ""


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def fields_table(schema: dict, refs: set) -> list[str]:
    props = schema.get("properties", {})
    if not props:
        return ["Any JSON object." if schema.get("type") == "object" else f"{type_of(schema, refs)}."]
    required = set(schema.get("required", []))
    lines = ["| Field | Type | Required | Default | Notes |", "|---|---|---|---|---|"]
    for name, sub in props.items():
        lines.append(f"| `{name}` | {cell(type_of(sub, refs))} | {'yes' if name in required else 'no'} "
                     f"| {cell(default_of(sub))} | {cell(limits(sub))} |")
    return lines


def description_of(text: str, method: str, path: str) -> str:
    """The handler's docstring, minus the 'GET /servers — ' some of them start with."""
    text = textwrap.dedent(text or "").strip()
    text = re.sub(r"^(GET|POST|PUT|PATCH|DELETE|WS)(/(GET|POST|PUT|PATCH|DELETE))*\s+/\S*\s*(—|-|–)\s*", "", text)
    paras = [" ".join(p.split()) for p in re.split(r"\n\s*\n", text) if p.strip()]
    if paras:
        paras[0] = paras[0][0].upper() + paras[0][1:]
    return "\n\n".join(paras)


def anchor(method: str, path: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", f"{method} {path}".lower()).strip("-")


def spec_op(spec, op) -> dict:
    return spec["paths"].get(op["path"], {}).get(op["method"].lower(), {}) if op["in_schema"] else {}


def summary_of(spec, op) -> str:
    library = LIBRARY_ROUTES.get(op["path"])
    text = library[1] if library else description_of(spec_op(spec, op).get("description") or inspect.getdoc(op["endpoint"]) or "", "", "")
    return first_sentence(text) if text else "—"


def sections(group):
    """One section per handler and path: a route that takes several methods is described once."""
    out: dict = {}
    for op in group:
        out.setdefault((op["path"], id(op["endpoint"]), op["method"] == "WS"), []).append(op)
    return list(out.values())


def render_op(ops, spec, auth, describe) -> tuple[list[str], set]:
    op = ops[0]
    method, path, fn = " ".join(o["method"] for o in ops), op["path"], op["endpoint"]
    sops = [spec_op(spec, o) for o in ops]
    sop = dict(sops[0])
    for other in sops[1:]:
        for key in ("parameters", "requestBody"):
            sop.setdefault(key, other.get(key)) if other.get(key) else None
    refs: set = set()
    out = [f'<a id="{anchor(o["method"], path)}"></a>' for o in ops] + [f"### `{method} {path}`", ""]
    library = LIBRARY_ROUTES.get(path)
    desc = library[1] if library else description_of(sop.get("description") or inspect.getdoc(fn) or "", method, path)
    if desc:
        out += [desc, ""]
    facts = []
    if library:
        facts.append(f"Served by {library[0]}")
    else:
        rel = os.path.relpath(inspect.getsourcefile(inspect.unwrap(fn)), ROOT)
        facts.append(f"Handler: [`{fn.__name__}`](../../../{rel})")
    gate = opt_in(path)
    if gate:
        facts.append(f"Mounted only with {gate}")
    if not op["in_schema"] and op["method"] != "WS":
        facts.append("Not listed in `/openapi.json`")
    facts.append("Access: " + "; ".join(access(path, auth)))
    out += [f"- {f}" for f in facts] + [""]

    params = sop.get("parameters", [])
    if params:
        out += ["**Parameters**", "", "| Name | In | Type | Required | Default | Notes |", "|---|---|---|---|---|---|"]
        for p in params:
            s = p.get("schema", {})
            notes = limits(s) or " ".join((p.get("description") or "").split())
            out.append(f"| `{p['name']}` | {p['in']} | {cell(type_of(s, refs))} | {'yes' if p.get('required') else 'no'} "
                       f"| {cell(default_of(s))} | {cell(notes)} |")
        out.append("")
    body = sop.get("requestBody")
    if body:
        for media, content in body.get("content", {}).items():
            schema = content.get("schema", {})
            name = schema.get("$ref", "").rsplit("/", 1)[-1]
            resolved = spec["components"]["schemas"].get(name, schema) if name else schema
            req = "required" if body.get("required") else "optional"
            label = f"`{name}`" if name and not name.startswith("Body_") else "form"
            out += [f"**Request body** ({req}, `{media}`, {label if media != 'application/json' or name else 'JSON'})", ""]
            out += fields_table(resolved, refs) + [""]

    out += ["**Response**", ""]
    success = {k: v for k, v in sop.get("responses", {}).items() if k.startswith("2")}
    typed = [(k, c.get("schema")) for k, v in success.items() for c in v.get("content", {}).values() if c.get("schema")]
    for code, schema in typed:
        out.append(f"- `{code}`: {type_of(schema, refs)} (typed in the spec)")
    node = node_of(fn) if not library else None
    if library:
        out.append("- `200`: " + ("Prometheus text format" if path == "/metrics" else "the OpenAPI document"))
        describe.stats["library"] += len(ops)
    elif op["method"] == "WS":
        out.append(f"- WebSocket. Protocol: {WS_PROTOCOLS.get(path, 'see the handler')}.")
    elif node is not None:
        shapes = describe.returns(fn, node)
        if not shapes:
            out.append("- `200`: `null` (no body)")
        for text, ok in shapes:
            out.append(f"- `200`: {text}" + ("" if ok else " (returned as is; see the handler)"))
        how = [ok for _, ok in shapes] or [True]
        describe.stats["source" if all(h is True for h in how) else "partly" if False in how else "doc"] += len(ops)
    out.append("")

    errs = []
    for dep in getattr(getattr(op["route"], "dependant", None), "dependencies", []) or []:
        call = getattr(dep, "call", None)
        if call is not None and (getattr(call, "__module__", "") or "").startswith("backend."):
            errs += raises(call)
    if node is not None:
        errs += raises(fn, node)
    if "422" in sop.get("responses", {}):
        errs.append((422, "The parameters or body don't match the tables above (FastAPI's `detail` list)", "validation"))
    seen, rows = set(), []
    for status, detail, where in sorted(errs, key=lambda e: (str(e[0]), e[1], e[2])):
        if (status, detail) in seen:
            continue
        seen.add((status, detail))
        rows.append(f"| {status} | {cell(detail) or '—'} | `{where}` |" if where != "validation" else f"| {status} | {cell(detail)} | FastAPI |")
    if rows:
        out += ["**Errors** (plus the [access errors](../README.md#errors) every route can return)", "",
                "| Status | Detail | Raised in |", "|---|---|---|"] + rows + [""]
    return out, refs


def schema_section(name, spec, refs_out) -> list[str]:
    schema = spec["components"]["schemas"][name]
    refs: set = set()
    lines = [f'<a id="schema-{name.lower()}"></a>', f"#### `{name}`", ""] + fields_table(schema, refs) + [""]
    refs_out |= refs
    return lines


def codebase_tools() -> list[str]:
    """The JSON-RPC tools behind /api/mcp-codebase, from the manifest tools/list returns."""
    from backend.routers import mcp_codebase
    from backend.services import tool_policy
    lines = ["## Tools (`tools/list`)", "",
             "JSON-RPC 2.0: `{\"jsonrpc\": \"2.0\", \"id\": 1, \"method\": \"tools/call\", \"params\": {\"name\": ..., "
             "\"arguments\": {...}}}`. A call's tier is the one the chat tool loop uses; a tier that needs approval is "
             "refused when called directly over HTTP (`DENIED: ...`), because approval lives in the chat and gateway "
             "tool loops. In a packaged build every call answers error -32000.", "",
             "| Tool | Tier | Direct HTTP call | What it does |", "|---|---|---|---|"]
    details = []
    for tool in mcp_codebase.TOOLS:
        tier = tool_policy.classify_mcp_tool("codebase", {"in_process": "codebase"}, tool["name"])
        direct = "refused" if tool_policy.requires_approval(tier) else "allowed"
        lines.append(f"| [`{tool['name']}`](#tool-{tool['name'].replace('_', '-')}) | {tier} | {direct} "
                     f"| {cell(first_sentence(tool.get('description', '')))} |")
        refs: set = set()
        details += [f'<a id="tool-{tool["name"].replace("_", "-")}"></a>', f"#### `{tool['name']}`", "",
                    " ".join(tool.get("description", "").split()), ""] + fields_table(tool["inputSchema"], refs) + [""]
    return lines + [""] + details


def build(app, auth, tables) -> dict[str, str]:
    spec = app.openapi()
    ops = collect(app)
    describe = Describer(tables)
    areas: dict[str, list] = {}
    for op in ops:
        areas.setdefault(op["area"], []).append(op)
    files = {}
    index = [GENERATED, "", "# HTTP and WebSocket reference", "",
             f"{sum(o['method'] != 'WS' for o in ops)} HTTP operations and {sum(o['method'] == 'WS' for o in ops)} "
             f"WebSockets, in {len(areas)} areas, generated from the backend's OpenAPI spec and its route handlers. "
             "Start with the [overview](../README.md) for access rules, errors and the WebSocket protocols.", "",
             "| Area | Operations | What it does |", "|---|---|---|"]
    order = sorted(areas, key=lambda a: (a != "app", a))
    for area in order:
        group = sorted(areas[area], key=lambda o: (o["path"], METHODS.index(o["method"].lower()) if o["method"].lower() in METHODS else 9))
        module = inspect.getmodule(inspect.unwrap(group[0]["endpoint"]))
        intro = description_of(module.__doc__ or "", "", "").split("\n\n")[0] if area != "app" else (
            "The routes outside `/api`: the backend's own status, Prometheus metrics, Design Center's HTML tools and "
            "the pictures social platforms fetch for a post.")
        prefix = next((p for p in OPT_IN if group[0]["path"].startswith(p)), None)
        lines = [GENERATED, "", f"# `{area}`" + (f" — `/api/{area}`" if area != "app" else " — top-level routes"), ""]
        if intro:
            lines += [intro, ""]
        if prefix:
            lines += [f"Mounted only with {OPT_IN[prefix]}.", ""]
        lines += ["| Method | Path | Summary |", "|---|---|---|"]
        for sec in sections(group):
            o = sec[0]
            methods = ", ".join(x["method"] for x in sec)
            lines.append(f"| {methods} | [`{o['path']}`](#{anchor(o['method'], o['path'])}) | {cell(summary_of(spec, o))} |")
        lines.append("")
        refs: set = set()
        for sec in sections(group):
            body, r = render_op(sec, spec, auth, describe)
            lines += body
            refs |= r
        if area == "mcp-codebase":
            lines += codebase_tools()
        if refs:
            lines += ["## Schemas", ""]
            done: set = set()
            while refs - done:
                name = sorted(refs - done)[0]
                done.add(name)
                lines += schema_section(name, spec, refs)
        files[f"http/{area}.md"] = "\n".join(lines).rstrip() + "\n"
        first = (description_of(module.__doc__ or "", "", "").split("\n\n")[0] if area != "app" else intro)
        index.append(f"| [`{area}`]({area}.md) | {len(group)} | {cell(first_sentence(first)) if first else '—'} |")
    st = describe.stats
    index[6:6] = [f"The spec types no successful response, so each one is read from its handler. Of the "
                  f"{sum(st.values())} HTTP operations, {st['source']} have their response shape read from the source, "
                  f"{st['doc']} are described by the docstring of the helper that builds the response, {st['library']} "
                  f"are served by libraries (described by hand), and for {st['partly']} the reference shows the "
                  "expression the handler returns (marked \"returned as is\") next to a link to the handler.", ""]
    files["http/README.md"] = "\n".join(index) + "\n"
    spec_out = json.loads(json.dumps(spec))
    ids = collections.Counter(op.get("operationId") for item in spec_out["paths"].values() for op in item.values())
    for path, item in spec_out["paths"].items():
        # A route taking several methods comes out of FastAPI in set order, all sharing one operationId
        # named after whichever method came first; fix both so the snapshot is valid and stable.
        item = spec_out["paths"][path] = {m: item[m] for m in sorted(item, key=lambda m: METHODS.index(m) if m in METHODS else 9)}
        for method, op in item.items():
            if ids[op.get("operationId")] > 1:
                op["operationId"] = re.sub(r"_(get|post|put|patch|delete|head)$", "", op["operationId"]) + "_" + method
        gate = opt_in(path)
        if gate:
            for op in item.values():
                op["x-arynwood-mounted-only-with"] = re.sub(r"[`]", "", gate)
    files["openapi.json"] = json.dumps(spec_out, indent=1, sort_keys=False, ensure_ascii=False) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the checked-in files instead of writing")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        app, auth, tables = load_backend(tmp)
        files = build(app, auth, tables)
    stale = []
    existing = {str(p.relative_to(OUT)) for p in (OUT / "http").glob("*.md")}
    for name, text in sorted(files.items()):
        path = OUT / name
        old = path.read_text() if path.exists() else ""
        if old != text:
            stale.append(name)
            if args.check:
                diff = difflib.unified_diff(old.splitlines(), text.splitlines(), f"a/{name}", f"b/{name}", lineterm="", n=1)
                print("\n".join(list(diff)[:40]))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for extra in sorted(existing - set(files)):
        stale.append(extra)
        if not args.check:
            (OUT / extra).unlink()
    if args.check and stale:
        print(f"Out of date: {', '.join(stale)}. Run: venv/bin/python scripts/gen_api_reference.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"Wrote {len(files)} files to {OUT.relative_to(ROOT)} ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
