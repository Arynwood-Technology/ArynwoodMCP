def walk(routes, prefix="", tags=()):
    for r in routes:
        if type(r).__name__ == "_IncludedRouter":  # FastAPI >= 0.141 keeps included routers whole
            ctx = r.include_context
            yield from walk(r.original_router.routes, prefix + ctx.prefix, tuple(ctx.tags or tags))
        elif getattr(r, "routes", None) is not None and hasattr(r, "include_router"):
            yield from walk(r.routes, prefix, tags)
        else:
            yield prefix, tags, r


def spec_path(path: str) -> str:
    return re.sub(r"\{(\w+):\w+\}", r"{\1}", path)


def collect(app):
    """One entry per (method, path) the app answers, plus each WebSocket."""
    ops = []
    for prefix, tags, r in walk(app.routes):
        path = spec_path(prefix + r.path)
        kind = type(r).__name__
        endpoint = getattr(r, "endpoint", None)
        area = tags[0] if tags else "app"
        if kind in ("APIWebSocketRoute", "WebSocketRoute"):
            ops.append({"method": "WS", "path": path, "area": area, "endpoint": endpoint, "route": r, "in_schema": False})
            continue
        for m in sorted(getattr(r, "methods", None) or ()):
            if m == "HEAD" and kind == "Route":
                continue  # Starlette adds HEAD to every plain GET route
            ops.append({"method": m, "path": path, "area": area, "endpoint": endpoint, "route": r,
                        "in_schema": getattr(r, "include_in_schema", kind == "APIRoute") and kind == "APIRoute"})
    return ops


def opt_in(path: str):
    return next((v for k, v in OPT_IN.items() if path == k or path.startswith(k + "/")), None)


def access(path: str, auth) -> list[str]:
    """Mirror of ApiKeyMiddleware's decisions (backend/services/auth.py) for one route."""
    sample = re.sub(r"\{\w+\}", "x", path)
    keyed = path == "/api" or path.startswith(("/api/", "/social-media/")) or path in ("/metrics", "/social-media")
    notes = ["this computer only, or the API key once `ARYNWOOD_API_KEY` is set" if keyed
             else "no key from this computer; the API key from any other"]
    if auth.CROSS_SITE_READ_ONLY.fullmatch(sample):
        notes.append("GET/HEAD allowed cross-site (the app's own media and frames)")
    if auth.SANDBOXED_READ_ONLY.fullmatch(sample):
        notes.append("GET/HEAD allowed from `Origin: null` (sandboxed website previews)")
    return notes


# ── source analysis ───────────────────────────────────────────────────────────

_trees: dict[str, ast.Module] = {}


def tree_of(fn):
    fn = inspect.unwrap(fn)
    path = inspect.getsourcefile(fn)
    if path not in _trees:
        _trees[path] = ast.parse(Path(path).read_text())
    return _trees[path], path


def node_of(fn):
    """The def (or lambda) node for a function object."""
    fn = inspect.unwrap(fn)
    try:
        tree, _ = tree_of(fn)
    except (TypeError, OSError):
        return None
    first = fn.__code__.co_firstlineno
    for n in ast.walk(tree):
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == fn.__name__:
            if (n.decorator_list[0].lineno if n.decorator_list else n.lineno) == first or n.lineno == first:
                return n
        if fn.__name__ == "<lambda>" and isinstance(n, ast.Lambda) and n.lineno == first:
            return n
    return None


def own_nodes(fn_node):
    """Nodes of a function body, not descending into nested defs or lambdas."""
    nested = (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)
    body = [fn_node.body] if isinstance(fn_node, ast.Lambda) else fn_node.body
    stack = [n for n in body if not isinstance(n, nested)]
    while stack:
        n = stack.pop()
        yield n
        for c in ast.iter_child_nodes(n):
            if not isinstance(c, nested):
                stack.append(c)


def is_backend(obj) -> bool:
    return inspect.isfunction(inspect.unwrap(obj)) if callable(obj) else False


def resolve(fn, expr):
    """The backend function object an expression names, seen from fn's module."""
    g = inspect.unwrap(fn).__globals__
    try:
        if isinstance(expr, ast.Name):
            obj = g.get(expr.id)
        elif isinstance(expr, ast.Attribute) and isinstance(expr.value, ast.Name):
            obj = getattr(g.get(expr.value.id), expr.attr, None)
        else:
            return None
    except Exception:
        return None
    if inspect.isfunction(obj) and (obj.__module__ or "").startswith("backend."):
        return obj
    return None


def nested_def(fn_node, name):
    for n in ast.walk(fn_node):
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == name and n is not fn_node:
            return n
    return None


def callee_name(call) -> str:
    f = call.func
    return f.attr if isinstance(f, ast.Attribute) else f.id if isinstance(f, ast.Name) else ""


def kwarg(call, name, pos=None):
    for k in call.keywords:
        if k.arg == name:
            return k.value
    if pos is not None and len(call.args) > pos:
        return call.args[pos]
    return None


def unparse(node) -> str:
    """ast.unparse, with f-strings written the same way on every Python version.

    Since PEP 701, Python 3.12's ast.unparse reuses an f-string's own quote inside a replacement field, so
    the same source came out as f"{d['k']}" on 3.11 and f'{d['k']}' on 3.12, and the pages differed with
    the interpreter. Each f-string here gets the first quote its body doesn't contain, as on 3.11."""
    found = []

    class Hide(ast.NodeTransformer):
        def visit_JoinedStr(self, n):
            found.append(n)
            return ast.Name(id=f"__fstring_{len(found) - 1}__")

    text = ast.unparse(Hide().visit(copy.deepcopy(node)))
    for i, n in enumerate(found):
        text = text.replace(f"__fstring_{i}__", _fstring(n), 1)
    return text


def _fstring(node: ast.JoinedStr) -> str:
    body = "".join(_fstring_part(v) for v in node.values)
    quotes = [q for q in ("'", '"', '"""', "'''") if q not in body] or ["'''"]
    quotes.sort(key=lambda q: bool(body) and q[0] == body[-1])
    return f"f{quotes[0]}{body}{quotes[0]}"


def _fstring_part(v) -> str:
    if isinstance(v, ast.Constant):
        return "".join(c * 2 if c in "{}" else "\\\\" if c == "\\" else
                       c if c.isprintable() else c.encode("unicode_escape").decode() for c in v.value)
    expr = unparse(v.value)
    conversion = f"!{chr(v.conversion)}" if v.conversion != -1 else ""
    spec = ":" + "".join(_fstring_part(p) for p in v.format_spec.values) if v.format_spec else ""
    return "{" + (" " if expr.startswith("{") else "") + expr + conversion + spec + "}"


def const(node):
    return node.value if isinstance(node, ast.Constant) else None


def text_of(node, fn, fn_node=None, depth=0) -> str:
    """A readable message for an HTTPException detail: the literal, a variable's or a helper's message."""
    if node is None:
        return ""
    if isinstance(node, ast.Constant):
        return str(node.value)
    if isinstance(node, ast.Call) and callee_name(node) == "str" and len(node.args) == 1:
        return "the underlying error's message"
    if isinstance(node, ast.Name) and fn_node is not None and depth < 3:
        for n in own_nodes(fn_node):
            if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == node.id for t in n.targets) \
                    and n.lineno < node.lineno:
                return text_of(n.value, fn, fn_node, depth + 1)
        g = inspect.unwrap(fn).__globals__.get(node.id)
        if isinstance(g, str):
            return g
    if isinstance(node, ast.Call) and depth < 3:
        target = resolve(fn, node.func)
        helper = node_of(target) if target is not None else None
        if helper is not None:
            for n in own_nodes(helper):
                if isinstance(n, ast.Return) and n.value is not None:
                    v = n.value.body if isinstance(n.value, ast.IfExp) else n.value
                    if isinstance(v, ast.Call) and isinstance(v.func, ast.Attribute) and v.func.attr == "format":
                        base = text_of(v.func.value, target, helper, depth + 1)
                        if base:
                            return base
            doc = ast.get_docstring(helper)
            if doc:
                return f"the message from `{target.__name__}()`: " + first_sentence(doc)
    if isinstance(node, ast.JoinedStr):
        out = []
        for v in node.values:
            out.append(str(v.value) if isinstance(v, ast.Constant) else "{" + unparse(v.value) + "}")
        return "".join(out)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return text_of(node.left, fn) + text_of(node.right, fn)
    return "{" + unparse(node) + "}"


def status_of(node, fn):
    if isinstance(node, ast.Constant):
        return node.value
    try:
        return int(eval(compile(ast.Expression(node), "<status>", "eval"), inspect.unwrap(fn).__globals__))
    except Exception:
        return unparse(node)


def raises(fn, fn_node=None, depth=0, seen=None):
    """(status, detail, where) for each HTTPException fn raises, or a backend helper it calls raises."""
    seen = seen if seen is not None else set()
    fn_node = fn_node or node_of(fn)
    if fn_node is None or id(fn_node) in seen:
        return []
    seen.add(id(fn_node))
    where = getattr(fn_node, "name", "a dependency")
    found = []
    for n in own_nodes(fn_node):
        if isinstance(n, ast.Raise) and isinstance(n.exc, ast.Call) and callee_name(n.exc) == "HTTPException":
            code = status_of(kwarg(n.exc, "status_code", 0), fn)
            detail = text_of(kwarg(n.exc, "detail", 1), fn, fn_node)
            if not detail and isinstance(code, int):
                detail = HTTPStatus(code).phrase  # FastAPI's default detail
            found.append((code, detail, where))
        elif isinstance(n, ast.Raise) and isinstance(n.exc, ast.Call) and resolve(fn, n.exc.func) is not None:
            # raise _unreachable(...): a helper that builds the HTTPException
            target = resolve(fn, n.exc.func)
            helper = node_of(target)
            for r in own_nodes(helper) if helper is not None else ():
                if isinstance(r, ast.Return) and isinstance(r.value, ast.Call) and callee_name(r.value) == "HTTPException":
                    code = status_of(kwarg(r.value, "status_code", 0), target)
                    found.append((code, text_of(kwarg(r.value, "detail", 1), target, helper), helper.name))
        elif isinstance(n, ast.Return) and isinstance(n.value, ast.Call) and callee_name(n.value) == "JSONResponse":
            code = kwarg(n.value, "status_code")
            if code is not None and str(status_of(code, fn)).startswith(("4", "5")):
                body = kwarg(n.value, "content", 0)
                found.append((status_of(code, fn), describe_inline(body), where))
        elif isinstance(n, ast.Call) and depth < 3:
            target = resolve(fn, n.func)
            if target is not None:
                found += raises(target, None, depth + 1, seen)
            elif isinstance(n.func, ast.Name):
                inner = nested_def(fn_node, n.func.id)
                if inner is not None:
                    found += raises(fn, inner, depth + 1, seen)
    return found


def describe_inline(node) -> str:
    if isinstance(node, ast.Dict):
        return "JSON with " + keys_of(node)
    return "`" + unparse(node) + "`" if node is not None else ""


def keys_of(d: ast.Dict) -> str:
    keys = []
    for k, v in zip(d.keys, d.values):
        if k is None:
            keys.append(f"the fields of `{unparse(v)}`")
        elif isinstance(k, ast.Constant):
            keys.append(f"`{k.value}`")
        else:
            keys.append(f"`[{unparse(k)}]`")
    return ", ".join(keys) if keys else "no fields"


SELECT = re.compile(r"^\s*SELECT\s+(.*?)\s+FROM\s+(\w+)", re.I | re.S)


# A thread-pool hop: what comes back is what the function handed to it returns.
