def load_backend(tmp: str):
    """Import the backend the way a fresh install sees it, with every optional router mounted."""
    env = {
        "ARYNWOOD_DB_PATH": os.path.join(tmp, "arynwood.db"),
        "ARYNWOOD_DISABLE_BACKGROUND_INDEX": "1",
        "ARYNWOOD_ENABLE_CODEBASE_TOOLS": "1",
        "ARYNWOOD_ENABLE_GATEWAY": "1",
        "ARYNWOOD_GATEWAY_CONFIG": os.path.join(tmp, "gateway.json"),
        "ARYNWOOD_PERSONAS_FILE": os.path.join(tmp, "personas.local.json"),
    }
    os.environ.update(env)
    sys.path.insert(0, str(ROOT))
    import warnings
    warnings.filterwarnings("ignore", message="Duplicate Operation ID")
    from backend import api, db
    from backend.services import auth
    asyncio.run(db.init_db())
    con = sqlite3.connect(env["ARYNWOOD_DB_PATH"])
    tables = {t: [c[1] for c in con.execute(f"PRAGMA table_info({t})")]
              for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
    con.close()
    return api.app, auth, tables


